    #[test]
    fn extract_cookie_finds_value() {
        let cookies = "other=foo; CF_Authorization=eyJhbGciOiJSUzI1NiJ9.test; bar=baz";
        assert_eq!(
            extract_cookie(cookies, "CF_Authorization"),
            Some("eyJhbGciOiJSUzI1NiJ9.test".to_string())
        );
    }

    #[test]
    fn extract_cookie_returns_none_when_missing() {
        let cookies = "other=foo; bar=baz";
        assert_eq!(extract_cookie(cookies, "CF_Authorization"), None);
    }

    #[test]
    fn extract_cookie_handles_single_cookie() {
        let cookies = "CF_Authorization=my-token";
        assert_eq!(
            extract_cookie(cookies, "CF_Authorization"),
            Some("my-token".to_string())
        );
    }

    #[test]
    fn render_connect_page_contains_token_and_code() {
        let html = render_connect_page(
            "gateway.example.com:8080",
            12345,
            "test-jwt-token",
            "ABC-1234",
            "test-nonce",
        );
        assert!(html.contains("test-jwt-token"));
        assert!(html.contains("12345"));
        assert!(html.contains("gateway.example.com:8080"));
        assert!(html.contains("OpenShell"));
        assert!(html.contains("ABC-1234"));
        // Should use fetch(), not window.location.href
        assert!(html.contains("fetch("));
        assert!(!html.contains("window.location.href"));
        // Should POST with JSON
        assert!(html.contains("method: 'POST'"));
        assert!(html.contains("JSON.stringify"));
        // CSP nonce should be on the script tag
        assert!(html.contains("nonce=\"test-nonce\""));
    }

    #[test]
    fn render_connect_page_escapes_special_chars() {
        let html = render_connect_page(
            "gw",
            1234,
            "token<script>alert('xss')</script>",
            "ABC-1234",
            "nonce",
        );
        // < and > should be escaped via JSON encoding (\u003c)
        assert!(!html.contains("<script>alert"));
    }

    #[test]
    fn render_connect_page_includes_code_in_js_payload() {
        let html = render_connect_page("gw", 1234, "jwt", "XY7-9KLM", "nonce");
        // The JS should send the code in the JSON payload (now JSON-encoded)
        assert!(html.contains(r#"var code = "XY7-9KLM""#));
        assert!(html.contains("code: code"));
    }

    #[test]
    fn is_valid_code_accepts_valid_format() {
        assert!(is_valid_code("AB7-X9KM"));
        assert!(is_valid_code("222-AAAA"));
        assert!(is_valid_code("ZZZ-9999"));
    }

    #[test]
    fn is_valid_code_rejects_invalid_format() {
        assert!(!is_valid_code(""));
        assert!(!is_valid_code("too-long-code"));
        assert!(!is_valid_code("abc-defg")); // lowercase
        assert!(!is_valid_code("AB7X9KLM")); // no dash
        assert!(!is_valid_code("AB7-9KL")); // too short
        assert!(!is_valid_code("x\u{2028};fetch('//evil')//")); // XSS payload
    }

    #[test]
    fn render_waiting_page_has_auto_refresh_with_code() {
        let html = render_waiting_page(12345, "ABC-1234");
        assert!(html.contains("meta http-equiv=\"refresh\""));
        assert!(html.contains("callback_port=12345"));
        assert!(html.contains("code=ABC-1234"));
    }

    #[test]
    fn render_waiting_page_escapes_code() {
        let html = render_waiting_page(1234, "x\"onload=\"alert(1)");
        // The double quote should be escaped so it can't break out of the
        // meta-refresh content attribute.
        assert!(!html.contains("x\"onload"));
        assert!(html.contains("&quot;"));
    }

    #[test]
    fn html_escape_basic() {
        assert_eq!(html_escape("hello"), "hello");
        assert_eq!(html_escape("<b>bold</b>"), "&lt;b&gt;bold&lt;/b&gt;");
        assert_eq!(html_escape("a&b"), "a&amp;b");
        assert_eq!(html_escape("a\"b"), "a&quot;b");
        assert_eq!(html_escape("a'b"), "a&#x27;b");
    }

    #[test]
    fn jwks_response_publishes_configured_gateway_key() {
        let material = generate_jwt_key().expect("key");
        let authenticator = crate::auth::sandbox_jwt::SandboxJwtAuthenticator::from_pem(
            material.public_key_pem.as_bytes(),
            material.kid.clone(),
            "gateway-a",
        )
        .expect("authenticator");

        let response = gateway_jwks_response(Some(&authenticator));
        assert_eq!(response.status(), StatusCode::OK);
        let key = &authenticator.jwks().keys[0];
        assert_eq!(key.kid, material.kid);
        assert_eq!(key.kty, "OKP");
        assert_eq!(key.crv, "Ed25519");
        assert_eq!(key.alg, "EdDSA");
        assert_eq!(key.key_use, "sig");
    }

    #[test]
    fn jwks_response_is_not_found_without_gateway_key() {
        assert_eq!(gateway_jwks_response(None).status(), StatusCode::NOT_FOUND);
    }

    fn test_authenticator() -> crate::auth::sandbox_jwt::SandboxJwtAuthenticator {
        let material = generate_jwt_key().expect("key");
        crate::auth::sandbox_jwt::SandboxJwtAuthenticator::from_pem(
            material.public_key_pem.as_bytes(),
            material.kid,
            "gateway-a",
        )
        .expect("authenticator")
    }

    #[tokio::test]
    async fn discovery_document_advertises_issuer_identity_and_absolute_jwks_uri() {
        let authenticator = test_authenticator();
        let response = gateway_discovery_response(
            Some(&authenticator),
            &Some("https://gateway.example:8443".to_string()),
        );
        assert_eq!(response.status(), StatusCode::OK);

        let body = to_bytes(response.into_body(), 64 * 1024)
            .await
            .expect("body");
        let document: serde_json::Value = serde_json::from_slice(&body).expect("json");

        // The issuer is the gateway identity, not the serving URL. Extensions
        // compare `iss` against this exact value.
        assert_eq!(document["issuer"], "openshell-gateway:gateway-a");
        assert_eq!(
            document["jwks_uri"],
            "https://gateway.example:8443/.well-known/jwks.json"
        );
        assert_eq!(
            document["id_token_signing_alg_values_supported"][0],
            "EdDSA"
        );
    }

    #[test]
    fn discovery_document_requires_a_key_and_a_resolvable_authority() {
        assert_eq!(
            gateway_discovery_response(None, &Some("https://gateway.example".to_string())).status(),
            StatusCode::NOT_FOUND
        );
        // A relative jwks_uri could be resolved against the wrong origin, so
        // refuse to emit a document rather than emit an ambiguous one.
        assert_eq!(
            gateway_discovery_response(Some(&test_authenticator()), &None).status(),
            StatusCode::BAD_REQUEST
        );
    }

    #[test]
    fn base_url_prefers_host_header_and_honours_forwarded_scheme() {
        let mut headers = HeaderMap::new();
        headers.insert(header::HOST, "gateway.example:8443".parse().unwrap());
        assert_eq!(
            document_base_url(&headers, &Uri::from_static("/")),
            Some("https://gateway.example:8443".to_string())
        );

        headers.insert("x-forwarded-proto", "http, https".parse().unwrap());
        assert_eq!(
            document_base_url(&headers, &Uri::from_static("/")),
            Some("http://gateway.example:8443".to_string())
        );

        // HTTP/2 has no Host header; axum surfaces `:authority` on the URI.
        assert_eq!(
            document_base_url(
                &HeaderMap::new(),
                &Uri::from_static("https://h2.example/.well-known/openid-configuration")
            ),
            Some("https://h2.example".to_string())
        );
        assert_eq!(
            document_base_url(&HeaderMap::new(), &Uri::from_static("/")),
            None
        );
    }
