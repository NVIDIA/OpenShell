//! Auth endpoint for edge-proxy browser-based login.
//!
//! When the CLI runs `gateway add` or `gateway login`, it opens the user's
//! browser to `GET /auth/connect?callback_port=<port>`. The edge proxy
//! (e.g., Cloudflare Access) intercepts the request and shows its `IdP` login
//! page. After authentication, the proxy sets the `CF_Authorization` cookie
//! and proxies the request to this endpoint.
//!
//! The handler reads the `CF_Authorization` cookie from the request headers
//! (required because the cookie is typically `HttpOnly`) and serves a styled
//! confirmation page. When the user clicks "Connect", JavaScript POSTs
//! the token to `http://127.0.0.1:<callback_port>/callback`, where the
//! CLI's ephemeral localhost server captures and stores the token.

use axum::{
    Json, Router,
    extract::{Query, State},
    http::{HeaderMap, StatusCode, Uri},
    response::{Html, IntoResponse},
    routing::get,
};
use http::header;
use serde::Deserialize;
use std::sync::Arc;

use crate::ServerState;

/// Validate that a confirmation code matches the CLI-generated format.
///
/// Codes are 3 alphanumeric characters, a dash, then 4 alphanumeric characters
/// (e.g., "AB7-X9KM"). The CLI generates these from the charset `[A-Z2-9]`.
fn is_valid_code(code: &str) -> bool {
    let bytes = code.as_bytes();
    bytes.len() == 8
        && bytes[3] == b'-'
        && bytes[..3]
            .iter()
            .all(|b| b.is_ascii_uppercase() || b.is_ascii_digit())
        && bytes[4..]
            .iter()
            .all(|b| b.is_ascii_uppercase() || b.is_ascii_digit())
}

#[derive(Deserialize)]
struct ConnectParams {
    callback_port: u16,
    /// One-time confirmation code generated by the CLI. Displayed on the
    /// connect page so the user can verify it matches their terminal before
    /// clicking Connect. Sent back in the XHR POST to the CLI callback
    /// server for cryptographic binding.
    code: String,
}

/// Create the auth router.
pub fn router(state: Arc<ServerState>) -> Router {
    Router::new()
        .route("/auth/connect", get(auth_connect))
        .route("/auth/oidc-config", get(oidc_config_handler))
        .route("/.well-known/jwks.json", get(gateway_jwks_handler))
        .route(
            "/.well-known/openid-configuration",
            get(gateway_discovery_handler),
        )
        .with_state(state)
}

/// Publish OIDC-shaped discovery metadata for extension services.
///
/// This lets an extension be configured with only the trusted gateway URL:
/// it learns the exact expected `iss` and the `jwks_uri` from one document
/// instead of having both provisioned separately.
///
/// Like the equivalent Kubernetes endpoint, this is OIDC-shaped rather than
/// OIDC-compliant: `issuer` is the gateway identity (`openshell-gateway:<id>`),
/// not the URL this document is served from. Verifiers must compare `iss`
/// against that value, and must not infer trust from the document's location
/// alone. The serving TLS connection is what authenticates the gateway.
async fn gateway_discovery_handler(
    State(state): State<Arc<ServerState>>,
    headers: HeaderMap,
    uri: Uri,
) -> impl IntoResponse {
    gateway_discovery_response(
        state.sandbox_jwt_authenticator.as_deref(),
        &document_base_url(&headers, &uri),
    )
}

/// Reconstruct the externally visible base URL for absolute discovery links.
///
/// HTTP/1.1 carries `Host`; HTTP/2 carries `:authority`, which axum surfaces
/// on the request URI. A terminating proxy may report the original scheme in
/// `X-Forwarded-Proto`; otherwise assume TLS, since the extension contract
/// requires fetching this document over an authenticated connection.
fn document_base_url(headers: &HeaderMap, uri: &Uri) -> Option<String> {
    let authority = headers
        .get(header::HOST)
        .and_then(|value| value.to_str().ok())
        .filter(|host| !host.is_empty())
        .map(ToString::to_string)
        .or_else(|| uri.authority().map(ToString::to_string))?;
    let scheme = headers
        .get("x-forwarded-proto")
        .and_then(|value| value.to_str().ok())
        .and_then(|proto| proto.split(',').next())
        .map(str::trim)
        .filter(|proto| !proto.is_empty())
        .unwrap_or("https");
    Some(format!("{scheme}://{authority}"))
}

fn gateway_discovery_response(
    authenticator: Option<&crate::auth::sandbox_jwt::SandboxJwtAuthenticator>,
    base_url: &Option<String>,
) -> axum::response::Response {
    let Some(authenticator) = authenticator else {
        return StatusCode::NOT_FOUND.into_response();
    };
    let Some(base_url) = base_url else {
        // Without a usable authority the `jwks_uri` cannot be absolute, and a
        // relative value would be worse than none: a verifier could resolve it
        // against the wrong origin.
        return StatusCode::BAD_REQUEST.into_response();
    };
    Json(serde_json::json!({
        "issuer": authenticator.issuer(),
        "jwks_uri": format!("{base_url}/.well-known/jwks.json"),
        "id_token_signing_alg_values_supported": ["EdDSA"],
        "response_types_supported": ["id_token"],
        "subject_types_supported": ["public"],
        "scopes_supported": ["openid"],
        "claims_supported": [
            "iss", "aud", "sub", "iat", "exp", "jti", "caller_kind", "sandbox_id"
        ],
    }))
    .into_response()
}

/// Publish the gateway's JWT verification key for extension services.
///
/// Public keys are not secret. The HTTPS connection authenticates the
/// gateway from which an integration bootstraps this document; integrations
/// then cache keys by `kid` and refresh when an unfamiliar `kid` appears.
async fn gateway_jwks_handler(State(state): State<Arc<ServerState>>) -> impl IntoResponse {
    gateway_jwks_response(state.sandbox_jwt_authenticator.as_deref())
}

fn gateway_jwks_response(
    authenticator: Option<&crate::auth::sandbox_jwt::SandboxJwtAuthenticator>,
) -> axum::response::Response {
    authenticator.map_or_else(
        || StatusCode::NOT_FOUND.into_response(),
        |authenticator| Json(authenticator.jwks()).into_response(),
    )
}

/// OIDC configuration discovery endpoint.
///
/// Returns the OIDC issuer and audience when OIDC is configured on the server,
/// so CLI clients can auto-discover settings during `gateway add`.
async fn oidc_config_handler(State(state): State<Arc<ServerState>>) -> impl IntoResponse {
    state.config.oidc.as_ref().map_or_else(
        || StatusCode::NOT_FOUND.into_response(),
        |oidc| {
            Json(serde_json::json!({
                "issuer": oidc.issuer,
                "audience": oidc.audience,
            }))
            .into_response()
        },
    )
}

/// Handle the auth connect request.
///
/// Reads `CF_Authorization` from the cookie header (server-side extraction
/// handles `HttpOnly` cookies) and serves either a waiting page or a
/// styled confirmation page with the token embedded.
async fn auth_connect(
    State(state): State<Arc<ServerState>>,
    Query(params): Query<ConnectParams>,
    headers: HeaderMap,
) -> impl IntoResponse {
    // Reject codes that don't match the CLI-generated format to prevent
    // reflected XSS via crafted URLs.
    if !is_valid_code(&params.code) {
        return Html(
            "<html><body><p>Invalid confirmation code format.</p></body></html>".to_string(),
        )
        .into_response();
    }

    let cf_token = headers
        .get("cookie")
        .and_then(|v| v.to_str().ok())
        .and_then(|cookies| extract_cookie(cookies, "CF_Authorization"));

    // Prefer the Host header (set by Cloudflare Tunnel / reverse proxies)
    // so the page shows the external URL the user actually connected through
    // rather than the internal bind address (e.g. 0.0.0.0:8080).
    let gateway_display = headers
        .get("x-forwarded-host")
        .or_else(|| headers.get("host"))
        .and_then(|v| v.to_str().ok())
        .map_or_else(|| state.config.bind_address.to_string(), String::from);

    let safe_gateway = html_escape(&gateway_display);

    if let Some(token) = cf_token {
        let nonce = uuid::Uuid::new_v4().to_string();
        let csp = format!(
            "default-src 'none'; script-src 'nonce-{nonce}'; style-src 'unsafe-inline'; connect-src http://127.0.0.1:*"
        );
        (
            [(header::CONTENT_SECURITY_POLICY, csp)],
            Html(render_connect_page(
                &safe_gateway,
                params.callback_port,
                &token,
                &params.code,
                &nonce,
            )),
        )
            .into_response()
    } else {
        let csp = "default-src 'none'; style-src 'unsafe-inline'".to_string();
        (
            [(header::CONTENT_SECURITY_POLICY, csp)],
            Html(render_waiting_page(params.callback_port, &params.code)),
        )
            .into_response()
    }
}

/// Extract a named cookie value from a `Cookie` header string.
fn extract_cookie(cookies: &str, name: &str) -> Option<String> {
    cookies.split(';').find_map(|c| {
        let mut parts = c.trim().splitn(2, '=');
        let key = parts.next()?.trim();
        let val = parts.next()?.trim();
        if key == name {
            Some(val.to_string())
        } else {
            None
        }
    })
}

